-- ScadBuddy's own print library (#3827, plan 2026-10-17-native-print-library). Ids start at
-- 1 000 000 000, far above Bambuddy's, so a mount's cache keyed by file id never meets the
-- other backend's file (Ruling 1). A file's blob key is its own (`library-file-<id>`).
CREATE TABLE library_folders (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
    parent_id bigint REFERENCES library_folders (id) ON DELETE RESTRICT,
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE library_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
    folder_id bigint REFERENCES library_folders (id) ON DELETE SET NULL,
    name text NOT NULL,
    size bigint NOT NULL,
    sha256 text NOT NULL,
    blob_key text NOT NULL UNIQUE,
    media_type text NOT NULL,
    plates jsonb NOT NULL DEFAULT '[]',
    has_thumbnail boolean NOT NULL DEFAULT false,
    output_id text,
    filed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);
CREATE INDEX library_files_folder ON library_files (folder_id) WHERE deleted_at IS NULL;
CREATE INDEX library_files_output ON library_files (output_id) WHERE output_id IS NOT NULL;
CREATE INDEX library_files_trashed ON library_files (deleted_at) WHERE deleted_at IS NOT NULL;
