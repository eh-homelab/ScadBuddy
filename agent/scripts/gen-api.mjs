// Writes src/api/schema.d.ts from the backend's OpenAPI spec. Neither file is
// committed (#492), so typecheck, test and build run this first.
//
// The spec comes from `SCADBUDDY_OPENAPI_JSON` when it is set (the Dockerfile's
// `api-spec` stage exports it and this stage copies it in, with no Python
// here). Otherwise it is exported now from ../backend, which needs uv.
//
// openapi-typescript makes a property with a `default` required (`defaultNonNullable`),
// which is true of a response (the backend sends every field) but not of a request:
// FastAPI leaves a defaulted field out of `required`, and the body may leave it out.
// So a defaulted property of a schema only request bodies reach is optional (#6602).
// A schema a response reaches too keeps the response's shape.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { URL, fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import ts from 'typescript'

const pkg = fileURLToPath(new URL('..', import.meta.url))
const backend = fileURLToPath(new URL('../../backend', import.meta.url))
let spec = process.env.SCADBUDDY_OPENAPI_JSON
if (!spec) {
  spec = `${backend}/openapi.json`
  execFileSync('uv', ['run', '--frozen', 'python', '-m', 'scadbuddy.tools.export_openapi', spec], {
    cwd: backend,
    stdio: ['ignore', 'ignore', 'inherit'],
  })
}

const SCHEMAS = '#/components/schemas/'

/** Every component schema a `$ref` under `node` names, and the ones they name in turn. */
function reached(schemas, node, seen = new Set()) {
  if (Array.isArray(node)) {
    for (const v of node) reached(schemas, v, seen)
  } else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string' && v.startsWith(SCHEMAS)) {
        const name = v.slice(SCHEMAS.length)
        if (!seen.has(name)) {
          seen.add(name)
          reached(schemas, schemas[name], seen)
        }
      } else {
        reached(schemas, v, seen)
      }
    }
  }
  return seen
}

const doc = JSON.parse(readFileSync(spec, 'utf8'))
const schemas = doc.components?.schemas ?? {}
const operations = Object.values(doc.paths ?? {}).flatMap((item) => Object.values(item))
const requests = reached(schemas, operations.map((op) => op?.requestBody))
const responses = reached(schemas, operations.map((op) => op?.responses))

const ast = await openapiTS(doc, {
  transformProperty(property, schema, { path }) {
    if (!path?.startsWith(SCHEMAS) || property.questionToken || !('default' in schema)) return undefined
    const [name, key, ...deeper] = path.slice(SCHEMAS.length).split('/')
    if (deeper.length || !requests.has(name) || responses.has(name)) return undefined
    if (schemas[name].required?.includes(key)) return undefined
    return ts.factory.updatePropertySignature(
      property,
      property.modifiers,
      property.name,
      ts.factory.createToken(ts.SyntaxKind.QuestionToken),
      property.type,
    )
  },
})
writeFileSync(
  `${pkg}/src/api/schema.d.ts`,
  `/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n${astToString(ast)}`,
)
